def _ensure_writable_dir(path):
    """Papka yo'q bo'lsa yaratadi. Yozib bo'lmasa False qaytaradi."""
    try:
        path.mkdir(parents=True, exist_ok=True)
        return os.access(path, os.W_OK)
    except OSError:
        return False


# Ko'rsatilgan papka mavjud bo'lmasa yoki yozib bo'lmasa, SQLite "unable to open database file" bilan qulamasin
