# Database
# https://docs.djangoproject.com/en/6.1/ref/settings/#databases

def _database():
    url = os.getenv('DATABASE_URL', '').strip()
    if url:
        from urllib.parse import urlparse, unquote
        u = urlparse(url)
        return {
            'ENGINE': 'django.db.backends.postgresql',
            'NAME': u.path.lstrip('/'),
            'USER': unquote(u.username or ''),
            'PASSWORD': unquote(u.password or ''),
            'HOST': u.hostname,
            'PORT': u.port or 5432,
            'CONN_MAX_AGE': 60,
            'CONN_HEALTH_CHECKS': True,
        }
    path = DATA_STORAGE_PATH / 'db.sqlite3'
    return {
        'ENGINE': 'django.db.backends.sqlite3',
        'NAME': path,
        'OPTIONS': {
            'timeout': 30,
            'transaction_mode': 'IMMEDIATE',
            # WAL: o'qish yozishni bloklamaydi — ko'p foydalanuvchi bir vaqtda ishlaganda "database is locked" bo'lmaydi
            'init_command': 'PRAGMA journal_mode=WAL; PRAGMA synchronous=NORMAL; PRAGMA busy_timeout=30000;',
        },
    }


DATABASES = {'default': _database()}


